"""
api/setup.py — the first-run setup wizard's backend (Phase C).

Local-first trust model: this runs on localhost for the machine's owner, so
writing ~/.tickerlens/config.toml and .env from the wizard is appropriate —
secrets never leave the machine and never enter the repo. After save, config
live-reloads (config.reload()) so no restart is needed.
"""
from __future__ import annotations

import os
import stat

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

import config
from providers import registry
from providers.base import SUBSCRIPTIONS

router = APIRouter(prefix="/api/setup")


def _keys(provider: str) -> list[str]:
    """Env-var names a provider needs — derived from providers.base.SUBSCRIPTIONS
    (the single source of truth) so this file never hardcodes key names."""
    return [env for _name, env in SUBSCRIPTIONS.get(provider, {}).get("secrets", [])]


